#!/usr/bin/env node
/**
 * Writes the Netlify redirect file for the old blog, so the old post URLs
 * land on their new home on this domain.
 *
 *   node scripts/write-redirects.mjs [path-to-TechLiaison-checkout]
 *
 * The rules are generated from the archive data rather than written by hand,
 * so a post that is renamed, added or removed cannot leave a redirect
 * pointing at nothing.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, '..');

const repo = process.argv[2] ?? path.join(ROOT, '..', '..', 'TechLiaison');
const archive = JSON.parse(await readFile(path.join(ROOT, 'content', 'archive.json'), 'utf8'));
const site = JSON.parse(await readFile(path.join(ROOT, 'content', 'site.json'), 'utf8'));

const target = site.url;

const lines = [
  '# The old post URLs, redirected to their new home on the portfolio.',
  '# Generated by scripts/write-redirects.mjs — do not edit by hand.',
  '#',
  '# The Netlify site for this repository is not currently deployed, so these',
  '# rules are insurance rather than a live redirect. They cost nothing and',
  '# they are correct the moment the site is published again.',
  '',
  '/posts/*  ' + target + '/blog/:splat  301',
  '/posts    ' + target + '/archive/    301',
  '/         ' + target + '/archive/    301',
  '',
  '# One rule per post, so a slug that is renamed still resolves.',
  ...archive.posts.map((p) => `/posts/${p.slug}/  ${target}/blog/${p.slug}/  301`),
  '',
];

const outDir = path.join(repo, 'static');
await mkdir(outDir, { recursive: true });
const outFile = path.join(outDir, '_redirects');
await writeFile(outFile, lines.join('\n'), 'utf8');

console.log(`✓ wrote ${outFile}`);
console.log(`  ${archive.posts.length} post rules + 3 catch-alls, target ${target}`);
